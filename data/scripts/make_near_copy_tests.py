"""Test pieces for the near-copy warning (backend lib/fingerprint.js tooClose).

Each one is a disguised copy of a public-domain melody in data/piezas/famous-melodies.json: moved to another key,
mirrored upside down, started late, with notes changed, or cut to an excerpt. The musical fingerprint (|DFT| of the
pitch-class profile and the onset grid) does not change under any of those, so Stemma still warns: "this sounds a lot
like Ode to Joy by Beethoven". One control piece is an original tune and must NOT warn.

They are not contributions: author "Stemma test pieces", style tag "near-copy-demo" (the backend never names them as
the original of anything). Derived from public-domain works, so they stay Public Domain.

Deterministic. Run from the repo root:  python3 data/scripts/make_near_copy_tests.py
Writes data/piezas/near-copy-tests.json; load it into a database with `npm run db:seed` in backend/.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data/piezas/famous-melodies.json"
OUT = ROOT / "data/piezas/near-copy-tests.json"
AUTHOR = "Stemma test pieces"
TAGS = ["test", "near-copy-demo"]

famous = {p["id"]: p for p in json.loads(SOURCE.read_text())}


def bars_of(notas):
    return max(1, math.ceil(max(n["inicio"] + n["duracion"] for n in notas) / 4 - 1e-9))


def piece(pid, nombre, original, how, notas, tonalidad):
    o = famous[original]
    return {
        "id": pid,
        "nombre": nombre,
        "tipo": "melodia",
        "autor": AUTHOR,
        "licencia": "Public Domain",
        "fuente": (
            f"Near-copy test piece: {o['nombre']} ({original}) by {o['autor']}, {how}. "
            "Generated by data/scripts/make_near_copy_tests.py to show the near-copy warning; not a contribution."
        ),
        "tonalidad": tonalidad,
        "tempo": o["tempo"],
        "estilo": TAGS,
        "compases": bars_of(notas),
        "parent_id": None,  # on purpose: a fork would be credited, and the warning skips fork families
        "notas": notas,
    }


def notes(pid):
    return [dict(n) for n in famous[pid]["notas"]]


pieces = []

# 1. Same tune, another key: Ode to Joy up a fourth (C -> F).
pieces.append(piece("p-9001", "Joyful theme in F (test: transposed copy)", "p-502", "moved up a fourth to F major",
                    [{**n, "tono": n["tono"] + 5} for n in notes("p-502")], "F"))

# 2. Same tune, starting two beats late.
pieces.append(piece("p-9002", "Little star, late start (test: shifted copy)", "p-503", "every note two beats later",
                    [{**n, "inicio": n["inicio"] + 2} for n in notes("p-503")], "C"))

# 3. Same tune upside down: Für Elise mirrored around its first note (E5 = 76). A minor mirrors to E major.
pieces.append(piece("p-9003", "Elise upside down (test: inverted copy)", "p-501", "mirrored upside down around E5",
                    [{**n, "tono": 152 - n["tono"]} for n in notes("p-501")], "E"))

# 4. Three notes changed, one in every two-bar stretch (the check also compares 2-bar windows, so an untouched
# stretch would match 100%).
hb = notes("p-504")
hb[5]["tono"] += 2  # beat 4
hb[14]["tono"] += 2  # beat 13
hb[18]["tono"] += 2  # beat 17
pieces.append(piece("p-9004", "Birthday tune, three notes changed (test: edited copy)", "p-504", "with three notes each moved up a whole step", hb, "C"))

# 5. An excerpt in another key: the first two bars of In the Hall of the Mountain King, down a minor third.
mk = [{**n, "tono": n["tono"] - 3} for n in notes("p-512") if n["inicio"] < 8]
pieces.append(piece("p-9005", "Mountain march excerpt (test: excerpt in another key)", "p-512",
                    "its first two bars, down a minor third", mk, "G#m"))

# 6. Control: an original tune written for this test. It must not warn.
control = []
melody = [(69, 0, 1), (72, 1, 0.5), (71, 1.5, 0.5), (67, 2, 1.5), (64, 3.5, 0.5),
          (65, 4, 0.75), (69, 4.75, 0.25), (74, 5, 1), (72, 6, 0.5), (69, 6.5, 1.5),
          (71, 8, 0.5), (74, 8.5, 0.5), (76, 9, 1), (79, 10, 0.75), (77, 10.75, 1.25),
          (76, 12, 1), (72, 13, 0.5), (74, 13.5, 0.5), (69, 14, 2)]
for tono, inicio, dur in melody:
    control.append({"tono": tono, "inicio": inicio, "duracion": dur, "velocidad": 0.8})
pieces.append({
    "id": "p-9006",
    "nombre": "Original tune (test control: no warning)",
    "tipo": "melodia",
    "autor": AUTHOR,
    "licencia": "CC BY 4.0",
    "fuente": "Control for the near-copy warning: an original melody written for Stemma at DurHack 2026 "
              "(data/scripts/make_near_copy_tests.py). It should not trigger the warning.",
    "tonalidad": "Am",
    "tempo": 90,
    "estilo": TAGS,
    "compases": bars_of(control),
    "parent_id": None,
    "notas": control,
})

OUT.write_text(json.dumps(pieces, ensure_ascii=False, indent=2) + "\n")
print(f"wrote {len(pieces)} test pieces to {OUT.relative_to(ROOT)}")
