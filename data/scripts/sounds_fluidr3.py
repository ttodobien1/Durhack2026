"""Download the FluidR3_GM instrument samples used by the frontend, with full traceability.

Source:  gleitz/midi-js-soundfonts (pre-rendered FluidR3_GM, one mp3 per note)
         https://github.com/gleitz/midi-js-soundfonts
Author:  Frank Wen (FluidR3_GM.sf2)
License: CC BY 3.0 (stated in the gleitz README for the Fluid soundfont).
         Not MusyngKite / FatBoy from the same repo: those are CC BY-SA.

Output (served by Vite as static files):
  frontend/public/samples/fluidr3/<gm_instrument>/<note>.mp3
  frontend/public/samples/fluidr3/manifest.json   every file: url, sha256, bytes, license, author, date
  frontend/public/samples/CREDITS.md              human-readable credits for every sound the app plays

Re-runnable: files already on disk with the right sha256 are not downloaded again.
"""

import datetime as dt
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SAMPLES_DIR = ROOT / "frontend" / "public" / "samples"
OUT_DIR = SAMPLES_DIR / "fluidr3"
BASE_URL = "https://gleitz.github.io/midi-js-soundfonts/FluidR3_GM"

SOURCE = {
    "name": "FluidR3_GM (pre-rendered by gleitz/midi-js-soundfonts)",
    "author": "Frank Wen",
    "license": "CC BY 3.0",
    "license_url": "https://creativecommons.org/licenses/by/3.0/us/",
    "license_evidence": "https://github.com/gleitz/midi-js-soundfonts#readme (Fluid Soundfont section)",
    "repository": "https://github.com/gleitz/midi-js-soundfonts",
    "original_soundfont": "http://www.synthfont.com/SoundFonts/FluidR3_GM.sfArk",
    "changes": "None. Files are copied byte for byte from the repository's GitHub Pages site.",
}

# app instrument name (pista.instrumento) -> General MIDI instrument folder in the soundfont
INSTRUMENTS = {
    "rhodes": "electric_piano_1",
    "bajo_electrico": "electric_bass_finger",
    "bajo_synth": "synth_bass_1",
    "pad": "pad_2_warm",
    "vibrafono": "vibraphone",
}

# One sample every minor third (C, Eb, Gb, A) from A0 to C8; Tone.Sampler pitch-shifts the rest.
# The soundfont names sharps as flats ("Eb1", not "D#1").
NOTES = ["A0"] + [f"{n}{o}" for o in range(1, 8) for n in ("C", "Eb", "Gb", "A")] + ["C8"]

# Salamander is not downloaded (the app streams it from tonejs.github.io), but it is credited too.
OTHER_CREDITS = [
    {
        "instrument": "piano",
        "name": "Salamander Grand Piano",
        "author": "Alexander Holm",
        "license": "CC BY 3.0",
        "license_url": "https://creativecommons.org/licenses/by/3.0/",
        "license_evidence": "https://github.com/sfzinstruments/SalamanderGrandPiano#license",
        "served_from": "https://tonejs.github.io/audio/salamander/",
    },
]


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fetch(url: str) -> bytes:
    # curl uses the system certificates (this Python build has none).
    return subprocess.run(["curl", "-fsSL", url], check=True, capture_output=True).stdout


def load_manifest() -> dict:
    path = OUT_DIR / "manifest.json"
    return json.loads(path.read_text()) if path.exists() else {"files": []}


def credits_md(manifest: dict) -> str:
    by_inst = {}
    for f in manifest["files"]:
        by_inst.setdefault((f["instrument"], f["gm_instrument"]), []).append(f)
    lines = [
        "# Sound credits",
        "",
        "Every sampled sound the Stemma app plays. Generated by `data/scripts/sounds_fluidr3.py`;",
        "per-file URLs and sha256 hashes are in `fluidr3/manifest.json`.",
        "",
        f"## {SOURCE['name']}",
        "",
        f"- **Author:** {SOURCE['author']}",
        f"- **License:** [{SOURCE['license']}]({SOURCE['license_url']}) (evidence: {SOURCE['license_evidence']})",
        f"- **Repository:** {SOURCE['repository']}",
        f"- **Changes:** {SOURCE['changes']}",
        "",
        "| App instrument | GM instrument | Files | Folder |",
        "| --- | --- | --- | --- |",
    ]
    for (inst, gm), files in sorted(by_inst.items()):
        lines.append(f"| `{inst}` | `{gm}` | {len(files)} | `samples/fluidr3/{gm}/` |")
    for c in OTHER_CREDITS:
        lines += [
            "",
            f"## {c['name']}",
            "",
            f"- **App instrument:** `{c['instrument']}`",
            f"- **Author:** {c['author']}",
            f"- **License:** [{c['license']}]({c['license_url']}) (evidence: {c['license_evidence']})",
            f"- **Served from:** {c['served_from']} (not copied into the repo)",
        ]
    lines += [
        "",
        "## Synthesized sounds",
        "",
        "Drums, the default bass and the default lead are synthesized in `frontend/src/audio.js` with Tone.js;",
        "they use no recorded samples.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    old = {f["path"]: f for f in load_manifest()["files"]}
    files, downloaded, kept = [], 0, 0
    today = dt.date.today().isoformat()

    for inst, gm in INSTRUMENTS.items():
        for note in NOTES:
            rel = f"fluidr3/{gm}/{note}.mp3"
            path = SAMPLES_DIR / rel
            url = f"{BASE_URL}/{gm}-mp3/{note}.mp3"
            prev = old.get(rel)
            if prev and path.exists() and sha256(path.read_bytes()) == prev["sha256"]:
                files.append(prev)
                kept += 1
                continue
            data = fetch(url)
            if not data.startswith((b"ID3", b"\xff\xfb", b"\xff\xf3", b"\xff\xf2")):
                raise SystemExit(f"ERROR: {url} is not an mp3")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            files.append({"path": rel, "instrument": inst, "gm_instrument": gm, "note": note,
                          "url": url, "sha256": sha256(data), "bytes": len(data),
                          "downloaded": today})
            downloaded += 1

    manifest = {"source": SOURCE, "instruments": INSTRUMENTS, "files": files}
    (OUT_DIR / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    (SAMPLES_DIR / "CREDITS.md").write_text(credits_md(manifest), encoding="utf-8")

    total = sum(f["bytes"] for f in files)
    print("=== Report: FluidR3_GM samples ===")
    print(f"instruments: {len(INSTRUMENTS)}  notes each: {len(NOTES)}")
    print(f"files: {len(files)}  (downloaded {downloaded}, already present {kept})  total {total / 1e6:.1f} MB")
    print(f"written: {OUT_DIR.relative_to(ROOT)}/manifest.json, {SAMPLES_DIR.relative_to(ROOT)}/CREDITS.md")


if __name__ == "__main__":
    main()
